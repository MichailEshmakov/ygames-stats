interface Example {
  query: string;
  meaning: string;
}

const EXAMPLES: Example[] = [
  { query: 'кот, котик, котейка, кошка', meaning: 'любое из написаний — запятая читается как «или»' },
  { query: '(кот, кошка) и (ферма, огород)', meaning: 'пересечение: и про кота, и про ферму' },
  { query: 'ферма и не симулятор', meaning: 'про ферму, но без слова «симулятор»' },
  { query: '"три в ряд"', meaning: 'фраза целиком, а не три отдельных слова' },
  { query: 'симул*', meaning: 'слово с любым продолжением: «Симулятор», «симуляция»' },
];

export function SearchHelp() {
  return (
    <details className="help">
      <summary className="help__summary">Как искать</summary>
      <div className="help__body">
        <table className="help__examples">
          <tbody>
            {EXAMPLES.map(({ query, meaning }) => (
              <tr key={query}>
                <td>
                  <code>{query}</code>
                </td>
                <td className="help__meaning">{meaning}</td>
              </tr>
            ))}
          </tbody>
        </table>

        <ul className="help__rules">
          <li>
            <b>Запятая — это «или».</b> Так пишут разные написания одного и того же слова.
          </li>
          <li>
            <b>Операторы:</b> <code>и</code>, <code>или</code>, <code>не</code>. Понимаются и{' '}
            <code>and</code>, <code>or</code>, <code>not</code>, и значки <code>&amp;</code>,{' '}
            <code>|</code>, <code>!</code>.
          </li>
          <li>
            <b>Скобки</b> группируют: сначала «не», потом «и», потом «или». Без скобок{' '}
            <code>кот или кошка и ферма</code> прочтётся как <code>кот или (кошка и ферма)</code>.
          </li>
          <li>
            <b>Кавычки</b> ищут фразу целиком, подряд и в том же порядке.
          </li>
          <li>
            <b>Переключатель под полями</b> задаёт только то, что подставлять между двумя
            словами через пробел. На запятую, операторы и скобки он не влияет.
          </li>
          <li>
            <b>Окончания отбрасываются:</b> «ферма» находит «фермы», «ферме», «фермер». К корню
            может добавиться не больше трёх букв — иначе «кот» начал бы ловить «которая».
          </li>
          <li>
            <b>Звёздочка в конце</b> снимает ограничение на длину хвоста: <code>симул*</code>{' '}
            найдёт и «Симулятор», и «симуляция». Слово перед звёздочкой берётся как написано,
            окончания у него не отбрасываются, а продолжение может быть любым — поэтому{' '}
            <code>кот*</code> поймает заодно и «которая».
          </li>
          <li>
            <b>Галочки «где искать»</b> задают поля, по которым идут ключевые слова. Название,
            теги и категории включены сразу; описание и «как играть» — свободный текст, там
            бывает написано что угодно, поэтому их включают, когда нужен широкий охват. Чтобы
            искать только по названию, снимите все галочки, кроме «названию».
          </li>
        </ul>
      </div>
    </details>
  );
}
